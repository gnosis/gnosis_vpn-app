#!/usr/bin/env python3
# Generates src/assets/flags/ from the flag-icons package. Commit what it writes.
# Requires cwebp and rsvg-convert (on the devShell PATH on Linux).
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "src/assets/flags"
FLAG_ICONS = REPO / "node_modules/flag-icons"
COUNTRY_SRC = FLAG_ICONS / "flags/4x3"

# The UI paints flags in a 28x20 CSS px span (Flag.tsx), so 2x is 56x40.
RASTER_W, RASTER_H = 56, 40
# Vite inlines assets under this into the CSS; SVGs that fit stay vector.
INLINE_LIMIT = 4096


def optimize_svg(data: bytes) -> bytes:
    """Strip the parts of an SVG that never affect rendering."""
    text = data.decode("utf-8", "replace")
    text = re.sub(r"<\?xml.*?\?>", "", text, flags=re.S)
    text = re.sub(r"<!DOCTYPE.*?>", "", text, flags=re.S)
    text = re.sub(r"<!--.*?-->", "", text, flags=re.S)
    text = re.sub(r"<metadata\b.*?</metadata>", "", text, flags=re.S | re.I)
    text = re.sub(r"<sodipodi:namedview\b[^>]*/>", "", text, flags=re.I)
    text = re.sub(r">\s+<", "><", text)
    return text.strip().encode("utf-8")


def render(code: str, svg: Path, tmp: Path) -> str | None:
    """Vector when it fits the inline budget, otherwise a 2x WebP."""
    slim = optimize_svg(svg.read_bytes())
    if len(slim) < INLINE_LIMIT:
        (OUT / f"{code}.svg").write_bytes(slim)
        return f"{code}.svg"
    png, webp = tmp / "rast.png", tmp / "out.webp"
    png.unlink(missing_ok=True)
    webp.unlink(missing_ok=True)
    rasterize = ["rsvg-convert", "-w", str(RASTER_W), "-h", str(RASTER_H), "-a",
                 "--background-color=none", str(svg), "-o", str(png)]
    encode = ["cwebp", "-quiet", "-q", "85", str(png), "-o", str(webp)]
    for cmd in (rasterize, encode):
        if subprocess.run(cmd, capture_output=True).returncode != 0:
            return None
    (OUT / f"{code}.webp").write_bytes(webp.read_bytes())
    return f"{code}.webp"


BASE_CSS = """\
/* Generated by scripts/generate-flags.py -- do not edit. */
.fib,
.fi {
  background-size: contain;
  background-position: 50%;
  background-repeat: no-repeat;
}
.fi {
  position: relative;
  display: inline-block;
  width: 1.3333333333em;
  line-height: 1em;
}
.fi:before {
  content: "\\00a0";
}
"""


def main() -> int:
    if not COUNTRY_SRC.is_dir():
        print("flag-icons is not installed; run `deno install` first", file=sys.stderr)
        return 1

    OUT.mkdir(parents=True, exist_ok=True)
    for stale in list(OUT.glob("*.svg")) + list(OUT.glob("*.webp")):
        stale.unlink()

    rules, codes = [], []
    with tempfile.TemporaryDirectory() as tmp:
        for svg in sorted(COUNTRY_SRC.glob("*.svg")):
            code = svg.stem
            out_name = render(code, svg, Path(tmp))
            if out_name is None:
                print(f"  ! render failed: {code}", file=sys.stderr)
                continue
            rules.append(f'.fi-{code}{{background-image:url("./{out_name}")}}')
            codes.append(code)

    (OUT / "flags.css").write_text(BASE_CSS + "\n".join(rules) + "\n")
    (OUT / "codes.ts").write_text(
        "// Generated by scripts/generate-flags.py -- do not edit.\n"
        "export const FLAG_CODES: readonly string[] = [\n"
        + "".join(f'  "{c}",\n' for c in codes)
        + "];\n"
    )
    version = json.loads((FLAG_ICONS / "package.json").read_text())["version"]
    (OUT / "NOTICE.md").write_text(
        "# Flag art attribution\n\n"
        "Generated by `scripts/generate-flags.py` -- do not edit.\n\n"
        f"Flags come from [flag-icons](https://github.com/lipis/flag-icons) {version}:\n\n"
        "```\n" + (FLAG_ICONS / "LICENSE").read_text().strip() + "\n```\n"
    )

    total = sum(f.stat().st_size for f in OUT.iterdir() if f.is_file())
    print(f"wrote {len(codes)} flags to {OUT.relative_to(REPO)} ({total / 1024:.0f} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
