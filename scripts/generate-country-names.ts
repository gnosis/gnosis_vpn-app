// Writes src-tauri/src/country_names.rs, the country names src-tauri/src/exit_label.rs gives every exit.
// Run: nix develop --command deno run --allow-write=src-tauri/src/country_names.rs scripts/generate-country-names.ts
// The output is already in rustfmt's shape, so `nix fmt` leaves it alone.

const OUT = "src-tauri/src/country_names.rs";
const names = new Intl.DisplayNames("en", { type: "region", fallback: "none" });

const rows: string[] = [];
for (let a = 65; a <= 90; a++) {
  for (let b = 65; b <= 90; b++) {
    const code = String.fromCharCode(a, b);
    const name = names.of(code);
    if (name === undefined) continue;
    // Pasted into a Rust string literal unescaped.
    if (/["\\\p{Cc}]/u.test(name)) throw new Error(`${code}: ${name}`);
    rows.push(`        "${code}" => "${name}",`);
  }
}

const source =
  `//! Generated by scripts/generate-country-names.ts from \`Intl.DisplayNames("en")\`; do not edit.

/// English name of an upper-case two-letter region code.
pub fn country_name(code: &str) -> Option<&'static str> {
    Some(match code {
${rows.join("\n")}
        _ => return None,
    })
}
`;

await Deno.writeTextFile(OUT, source);
console.log(`wrote ${rows.length} names to ${OUT}`);
