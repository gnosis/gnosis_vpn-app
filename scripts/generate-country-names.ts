// Writes src-tauri/src/country_names.rs so the tray names countries exactly as
// the main window does (`Intl.DisplayNames("en")` in src/utils/destinations.ts).
// Run: nix develop --command deno run --allow-write=src-tauri/src/country_names.rs scripts/generate-country-names.ts
// then `nix fmt`.

const OUT = "src-tauri/src/country_names.rs";
const names = new Intl.DisplayNames("en", { type: "region", fallback: "none" });

const rows: string[] = [];
for (let a = 65; a <= 90; a++) {
  for (let b = 65; b <= 90; b++) {
    const code = String.fromCharCode(a, b);
    const name = names.of(code);
    if (name === undefined) continue;
    // JSON's \uXXXX is not a Rust escape, so only plain names are copied over.
    if (/["\\\p{Cc}]/u.test(name)) throw new Error(`${code}: ${name}`);
    rows.push(`        "${code}" => "${name}",`);
  }
}

const source =
  `//! Generated by scripts/generate-country-names.ts from \`Intl.DisplayNames("en")\`, the main window's source; do not edit.

/// English name of a two-letter region code, as the main window shows it.
pub fn country_name(code: &str) -> Option<&'static str> {
    Some(match code {
${rows.join("\n")}
        _ => return None,
    })
}
`;

await Deno.writeTextFile(OUT, source);
console.log(`wrote ${rows.length} names to ${OUT}`);
